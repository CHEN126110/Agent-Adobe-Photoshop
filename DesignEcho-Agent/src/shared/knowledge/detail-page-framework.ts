/**
 * 按焦点取详情页框架内容；不传焦点返回全量（带小标题）。
 */
export function buildDetailPageFrameworkSummary(focus?: DetailPageFrameworkFocus | 'all'): string {
    if (focus && focus !== 'all' && DETAIL_PAGE_FRAMEWORK_SECTIONS[focus]) {
        const section = DETAIL_PAGE_FRAMEWORK_SECTIONS[focus];
        return `## ${section.title}\n${section.content}`;
    }
    return (Object.keys(DETAIL_PAGE_FRAMEWORK_SECTIONS) as DetailPageFrameworkFocus[])
        .map((key) => `## ${DETAIL_PAGE_FRAMEWORK_SECTIONS[key].title}\n${DETAIL_PAGE_FRAMEWORK_SECTIONS[key].content}`)
        .join('\n\n');
}

